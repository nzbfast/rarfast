#[cfg(feature = "parallel")]
#[test]
#[ignore = "FUZZ-08OCT-3: fails at 46a1d5bd5 (262144 bytes against 0); un-ignore with the fix"]
fn both_arms_deliver_the_same_bytes_before_the_error() {
    use rarkit::internals::rar5;
    const UNPACKED: u64 = 1 << 18;
    const WINDOW: u64 = 1 << 20;
    let serial = rar5::decode_member_probe(&MEMBER, UNPACKED, WINDOW, 0, false);
    let tape = rar5::decode_member_probe(&MEMBER, UNPACKED, WINDOW, 0, true);
    assert_eq!(serial.1, tape.1, "the two arms disagree on the error kind");
    assert_eq!(
        serial.0.len(),
        tape.0.len(),
        "the two arms stop at different output positions, both with {:?}",
        serial.1
    );
    assert!(serial.0 == tape.0, "the two arms disagree on the bytes");
}
